use std::path::Path;

use crate::naming::{route_path, variant_name};
use crate::scan::PageDir;
use crate::segment::Segment;

/// Generates the Rust source with the `Route` enum.
/// Expects a tree already passed through `read_signatures` and `check_collisions`.
pub fn generate(root: &PageDir) -> String {
    let mut out = Output::default();
    emit(root, &mut Vec::new(), 2, &mut out);

    // A trailing `#[end_layout]` has no variant to attach to, and the
    // derive closes open layouts at the end of the enum anyway.
    while out.variants.last().is_some_and(|l| l.trim() == "#[end_layout]") {
        out.variants.pop();
    }

    format!(
        "// @generated by odos-build. Do not edit.\n\
         mod __odos {{\n    \
             use dioxus::prelude::*;\n\n\
         {mods}\n    \
             #[rustfmt::skip]\n    \
             #[derive(Routable, Clone, PartialEq, Debug)]\n    \
             pub enum Route {{\n\
         {variants}\n    \
             }}\n\
         }}\n\
         pub use __odos::Route;\n",
        mods = out.mods,
        variants = out.variants.join("\n"),
    )
}

#[derive(Default)]
struct Output {
    /// `#[path = "..."] mod ...;` lines.
    mods: String,
    /// Attribute and variant lines inside `enum Route`.
    variants: Vec<String>,
    layout_count: usize,
}

impl Output {
    fn add_mod(&mut self, name: &str, file: &Path) {
        // `{:?}` prints the path as an escaped Rust string literal
        self.mods += &format!("    #[path = {:?}]\n    mod {name};\n", file.display().to_string());
    }
}

fn emit<'a>(dir: &'a PageDir, segments: &mut Vec<&'a Segment>, depth: usize, out: &mut Output) {
    if !has_routes(dir) {
        return; // no empty `#[layout]` blocks
    }
    if let Some(s) = &dir.segment {
        segments.push(s);
    }
    let pad = "    ".repeat(depth);

    let inner = if dir.has_layout {
        let module = format!("layout_{}", out.layout_count);
        out.layout_count += 1;
        out.add_mod(&module, &dir.path.join("layout.rs"));
        out.variants.push(format!("{pad}#[layout({module}::Layout)]"));
        depth + 1
    } else {
        depth
    };
    let ipad = "    ".repeat(inner);

    if dir.has_page {
        let variant = variant_name(segments);
        let module = format!("page_{}", to_snake(&variant));
        out.add_mod(&module, &dir.path.join("page.rs"));

        let fields: Vec<String> = dir.page_params.iter().map(|p| format!("{}: {}", p.name, p.ty)).collect();
        let fields = if fields.is_empty() { "{}".into() } else { format!("{{ {} }}", fields.join(", ")) };

        out.variants.push(format!("{ipad}#[route({:?}, {module}::Page)]", route_path(segments)));
        out.variants.push(format!("{ipad}{variant} {fields},"));
    }

    for child in &dir.children {
        emit(child, segments, inner, out);
    }

    // Last, so every other route is tried first. Inside the root layout.
    if dir.segment.is_none() && dir.has_not_found {
        out.add_mod("not_found", &dir.path.join("not_found.rs"));
        out.variants.push(format!("{ipad}#[route(\"/:..segments\", not_found::NotFound)]"));
        out.variants.push(format!("{ipad}NotFound {{ segments: Vec<String> }},"));
    }

    if dir.has_layout {
        out.variants.push(format!("{pad}#[end_layout]"));
    }
    if dir.segment.is_some() {
        segments.pop();
    }
}

fn has_routes(dir: &PageDir) -> bool {
    dir.has_page || dir.has_not_found || dir.children.iter().any(has_routes)
}

/// `BlogSlug` → `blog_slug`.
fn to_snake(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.extend(c.to_lowercase());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scan::scan;
    use crate::signature::read_signatures;
    use std::fs;
    use tempfile::TempDir;

    const NO_PARAMS: &str = "pub fn Page() -> Element { todo!() }";
    const LAYOUT: &str = "pub fn Layout() -> Element { todo!() }";

    /// Writes the files, runs the pipeline and replaces the temp path with `$ROOT`.
    fn generate_for(files: &[(&str, &str)]) -> String {
        let tmp = TempDir::new().unwrap();
        for (path, source) in files {
            let full = tmp.path().join(path);
            fs::create_dir_all(full.parent().unwrap()).unwrap();
            fs::write(full, source).unwrap();
        }
        let mut root = scan(tmp.path()).unwrap();
        read_signatures(&mut root).unwrap();
        generate(&root).replace(&tmp.path().display().to_string(), "$ROOT")
    }

    #[test]
    fn snake_case() {
        assert_eq!(to_snake("Index"), "index");
        assert_eq!(to_snake("BlogSlug"), "blog_slug");
        assert_eq!(to_snake("Page2024"), "page2024");
    }

    #[test]
    fn single_page() {
        assert_eq!(
            generate_for(&[("page.rs", NO_PARAMS)]),
            r#"// @generated by odos-build. Do not edit.
mod __odos {
    use dioxus::prelude::*;

    #[path = "$ROOT/page.rs"]
    mod page_index;

    #[rustfmt::skip]
    #[derive(Routable, Clone, PartialEq, Debug)]
    pub enum Route {
        #[route("/", page_index::Page)]
        Index {},
    }
}
pub use __odos::Route;
"#
        );
    }

    #[test]
    fn full_example() {
        assert_eq!(
            generate_for(&[
                ("layout.rs", LAYOUT),
                ("page.rs", NO_PARAMS),
                ("not_found.rs", "pub fn NotFound(segments: Vec<String>) -> Element { todo!() }"),
                ("sobre/page.rs", NO_PARAMS),
                ("(admin)/painel/page.rs", NO_PARAMS),
                ("_components/card.rs", ""),
                ("blog/layout.rs", LAYOUT),
                ("blog/page.rs", NO_PARAMS),
                ("blog/[slug]/page.rs", "pub fn Page(slug: String) -> Element { todo!() }"),
                ("blog/[...rest]/page.rs", "pub fn Page(rest: Vec<String>) -> Element { todo!() }"),
            ]),
            r#"// @generated by odos-build. Do not edit.
mod __odos {
    use dioxus::prelude::*;

    #[path = "$ROOT/layout.rs"]
    mod layout_0;
    #[path = "$ROOT/page.rs"]
    mod page_index;
    #[path = "$ROOT/(admin)/painel/page.rs"]
    mod page_painel;
    #[path = "$ROOT/blog/layout.rs"]
    mod layout_1;
    #[path = "$ROOT/blog/page.rs"]
    mod page_blog;
    #[path = "$ROOT/blog/[...rest]/page.rs"]
    mod page_blog_rest;
    #[path = "$ROOT/blog/[slug]/page.rs"]
    mod page_blog_slug;
    #[path = "$ROOT/sobre/page.rs"]
    mod page_sobre;
    #[path = "$ROOT/not_found.rs"]
    mod not_found;

    #[rustfmt::skip]
    #[derive(Routable, Clone, PartialEq, Debug)]
    pub enum Route {
        #[layout(layout_0::Layout)]
            #[route("/", page_index::Page)]
            Index {},
            #[route("/painel", page_painel::Page)]
            Painel {},
            #[layout(layout_1::Layout)]
                #[route("/blog", page_blog::Page)]
                Blog {},
                #[route("/blog/:..rest", page_blog_rest::Page)]
                BlogRest { rest: Vec < String > },
                #[route("/blog/:slug", page_blog_slug::Page)]
                BlogSlug { slug: String },
            #[end_layout]
            #[route("/sobre", page_sobre::Page)]
            Sobre {},
            #[route("/:..segments", not_found::NotFound)]
            NotFound { segments: Vec<String> },
    }
}
pub use __odos::Route;
"#
        );
    }

    #[test]
    fn layout_without_pages_is_skipped() {
        let code = generate_for(&[("page.rs", NO_PARAMS), ("empty/layout.rs", LAYOUT)]);
        assert!(!code.contains("layout"), "{code}");
    }
}
